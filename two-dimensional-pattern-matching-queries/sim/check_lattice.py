"""Patterns that are periodic along a lattice.
Condition (L): P[u] = P[u'] whenever u - u' lies in a subgroup Lambda of Z^2 that covers side m // 2 (every square of
that side meets every class). Instances: lattices with a basis v1, v2 with |v1|_inf + |v2|_inf <= m // 2, and random
lattices in Hermite normal form whose covering is checked by brute force. The lattice Pi generated by the periods of P of max-norm at most m/2 is then the group of all periods of the
doubly periodic extension Q of P. In a block B0 + [K)^2 of starts, K = m // 2, every window x + [m)^2 contains the
core B0 + K - 1 + [m - K + 1)^2, which holds a cell of every class of Z^2 / Pi. With r(g) the core cell of class g,
a cell w is a defect if T[w] != T[r(w mod Pi)]. The valid starts V (window free of defects) follow from the four
fronts of the defects around the cell B0 + K - 1, and the occurrences in the block are V intersected with one
class phi + Pi, where phi is the unique phase passing a deterministic sample of the copies of Q on the torus.
Checks against brute force."""
import math, random, sys
from math import gcd

def hnf(gens):
    """Lattice generated by gens as (d1, t, d2): basis (d1, 0), (t, d2), 0 <= t < d1; None if rank < 2."""
    rows = [list(g) for g in gens if g != (0, 0)]
    top = None
    flat = []
    for r in rows:
        if r[1] == 0:
            flat.append(r[0]); continue
        if top is None:
            top = r; continue
        a, b = top, r                                  # Euclid on the second coordinates
        while b[1] != 0:
            q = a[1] // b[1]
            a, b = b, [a[0] - q * b[0], a[1] - q * b[1]]
        top = a
        flat.append(b[0])
    if top is None:
        return None
    if top[1] < 0:
        top = [-top[0], -top[1]]
    d1 = 0
    for x in flat:
        d1 = gcd(d1, abs(x))
    if d1 == 0:
        return None
    return d1, top[0] % d1, top[1]

def cls(L, w):
    d1, t, d2 = L
    k = w[1] // d2
    return ((w[0] - k * t) % d1, w[1] - k * d2)

def classes(L):
    return [(i, j) for i in range(L[0]) for j in range(L[2])]

def add(L, g, h):
    return cls(L, (g[0] + h[0], g[1] + h[1]))

def neg(L, g):
    return cls(L, (-g[0], -g[1]))

def is_period(P, d):
    m = len(P)
    return all(P[i][j] == P[i + d[0]][j + d[1]] for i in range(max(0, -d[0]), min(m, m - d[0]))
               for j in range(max(0, -d[1]), min(m, m - d[1])))

def period_lattice(P):
    m = len(P); h = m // 2
    E = [(a, b) for a in range(-h, h + 1) for b in range(-h, h + 1) if (a, b) != (0, 0) and is_period(P, (a, b))]
    return hnf(E)

def torus_sample(L, Q):
    """Cells g_t, values c_t, survivor f: copy f (Q(g - f)) has c_t at g_t, every other copy differs somewhere."""
    G = classes(L)
    alive, ds = G[:], []
    while len(alive) > 1:
        s, u = alive[0], alive[-1]
        g = next(g for g in G if Q[add(L, g, neg(L, s))] != Q[add(L, g, neg(L, u))])
        part = {}
        for j in alive:
            part.setdefault(Q[add(L, g, neg(L, j))], []).append(j)
        c = min(part, key=lambda v: len(part[v]))
        ds.append((g, c)); alive = part[c]
    f = alive[0]
    assert len(ds) <= math.ceil(math.log2(len(G))) if len(G) > 1 else not ds
    for j in G:
        ok = all(Q[add(L, g, neg(L, j))] == c for g, c in ds)
        assert ok == (j == f)
    return f, ds

def pareto(pts):
    return [p for p in pts if not any(q != p and q[0] <= p[0] and q[1] <= p[1] for q in pts)]

def valid_from_fronts(defects, c0, m, K, n):
    """Starts x = c0 - a, a in [0, K)^2, whose window x + [m)^2 avoids the defects, from the four fronts only."""
    fronts = []
    for e1 in (True, False):
        for e2 in (True, False):
            q = [(abs(z[0] - c0[0]), abs(z[1] - c0[1])) for z in defects
                 if abs(z[0] - c0[0]) < m and abs(z[1] - c0[1]) < m
                 and ((z[0] - c0[0] >= 0) == e1) and ((z[1] - c0[1] >= 0) == e2)]
            for t in pareto(set(q)):
                fronts.append((t[0] if e1 else -t[0], t[1] if e2 else -t[1]))
    V = set()
    for a1 in range(K):
        for a2 in range(K):
            x = (c0[0] - a1, c0[1] - a2)
            if not (0 <= x[0] <= n - m and 0 <= x[1] <= n - m):
                continue
            if not any(-a1 <= z[0] <= m - 1 - a1 and -a2 <= z[1] <= m - 1 - a2 for z in fronts):
                V.add(x)
    return V

def occurs(T, P, x):
    m = len(P)
    return all(T[x[0] + i][x[1] + j] == P[i][j] for i in range(m) for j in range(m))

def covers(L, s):
    G = set(classes(L))
    return all({cls(L, (c[0] + i, c[1] + j)) for i in range(s) for j in range(s)} == G for c in classes(L))

def random_covering(rng, s):
    while True:
        d1, d2 = rng.randint(1, s), rng.randint(1, s)
        L = (d1, rng.randrange(d1), d2)
        if d1 * d2 <= s * s and covers(L, s):
            return L

def instance(rng, m, n):
    h = m // 2
    if h < 2 or rng.random() < 0.5:
        L0 = random_covering(rng, h)
    else:
        while True:
            a = rng.randint(1, h - 1)
            v1 = (rng.randint(-a, a), rng.randint(-a, a))
            b = rng.randint(1, h - max(abs(v1[0]), abs(v1[1])))
            v2 = (rng.randint(-b, b), rng.randint(-b, b))
            if max(map(abs, v1)) + max(map(abs, v2)) <= h and v1[0] * v2[1] - v1[1] * v2[0] != 0:
                break
        L0 = hnf([v1, v2])
    assert covers(L0, h)
    sigma = rng.choice([2, 2, 3])
    Q0 = {g: rng.randrange(sigma) for g in classes(L0)}
    P = [[Q0[cls(L0, (i, j))] for j in range(m)] for i in range(m)]
    T = [[rng.randrange(sigma) for _ in range(n)] for _ in range(n)]
    for _ in range(rng.randint(1, 4)):                 # periodic regions with random phases
        phi = (rng.randrange(50), rng.randrange(50))
        r0, c0 = rng.randrange(n - m + 1), rng.randrange(n - m + 1)
        r1, c1 = min(n, r0 + rng.randint(m, 3 * m)), min(n, c0 + rng.randint(m, 3 * m))
        for i in range(r0, r1):
            for j in range(c0, c1):
                T[i][j] = Q0[cls(L0, (i - phi[0], j - phi[1]))]
    for _ in range(rng.randint(0, 3)):                 # sparse noise
        T[rng.randrange(n)][rng.randrange(n)] = rng.randrange(sigma)
    if rng.random() < 0.1:                             # one-letter alphabet
        P = [[0] * m for _ in range(m)]; T = [[0] * n for _ in range(n)]
    return P, T, L0

def run(P, T, stats):
    m, n = len(P), len(T)
    K = m // 2
    L = period_lattice(P)
    assert L is not None
    G = classes(L)
    assert len(G) <= K * K
    Q = {}
    for i in range(m):                                 # P is Pi-periodic, and Pi is the full period group of Q
        for j in range(m):
            g = cls(L, (i, j))
            assert Q.setdefault(g, P[i][j]) == P[i][j]
    assert len(Q) == len(G)
    for s in G:
        if s != (0, 0):
            assert any(Q[add(L, g, s)] != Q[g] for g in G)
    f, ds = torus_sample(L, Q)
    occ = {(r, c) for r in range(n - m + 1) for c in range(n - m + 1) if occurs(T, P, (r, c))}
    for B0 in [(r, c) for r in range(0, n - m + 1, K) for c in range(0, n - m + 1, K)]:
        c0 = (B0[0] + K - 1, B0[1] + K - 1)
        core = [(c0[0] + i, c0[1] + j) for i in range(m - K + 1) for j in range(m - K + 1)]
        rep = {}
        for w in core:
            rep.setdefault(cls(L, w), w)
        assert len(rep) == len(G)                      # the core meets every class
        defects = [(i, j) for i in range(max(0, c0[0] - m + 1), min(n, c0[0] + m))
                   for j in range(max(0, c0[1] - m + 1), min(n, c0[1] + m))
                   if T[i][j] != T[rep[cls(L, (i, j))][0]][rep[cls(L, (i, j))][1]]]
        V = valid_from_fronts(defects, c0, m, K, n)
        block = {x for x in occ if B0[0] <= x[0] < B0[0] + K and B0[1] <= x[1] < B0[1] + K}
        assert block <= V
        QT = {g: T[w[0]][w[1]] for g, w in rep.items()}
        passing = [psi for psi in G
                   if all(QT[add(L, add(L, g, psi), neg(L, f))] == c for g, c in ds)]
        true = [phi for phi in G if all(QT[add(L, g, phi)] == Q[g] for g in G)]
        assert len(true) <= 1
        if true:
            assert passing == true
        assert block == ({x for x in V if cls(L, x) == true[0]} if true else set())
        found = None
        for psi in passing[:1]:
            cand = sorted(x for x in V if cls(L, x) == psi)
            if cand and occurs(T, P, cand[0]):
                found = cand[0]
        assert (found is not None) == bool(block)
        stats["blocks"] += 1; stats["occ_blocks"] += bool(block); stats["multi"] += len(block) > 1
        stats["maxD"] = max(stats["maxD"], len(G))

if __name__ == "__main__":
    rng = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
    stats = {"blocks": 0, "occ_blocks": 0, "multi": 0, "maxD": 0}
    cases = 0
    for it in range(400):
        m = rng.randint(2, 16)
        n = rng.randint(m, 3 * m + 4)
        P, T, L0 = instance(rng, m, n)
        L = period_lattice(P)
        assert cls(L, (L0[0], 0)) == (0, 0) and cls(L, (L0[1], L0[2])) == (0, 0)
        run(P, T, stats)
        cases += 1
    for m in (4, 6, 8):                                # constant patterns and all-equal texts
        P = [[0] * m for _ in range(m)]
        T = [[int(rng.random() < 0.08) for _ in range(3 * m)] for _ in range(3 * m)]
        run(P, T, stats); cases += 1
    print("cases", cases, stats)
    assert stats["occ_blocks"] > 50 and stats["multi"] > 20
    print("all checks passed")
