"""Strings (tensor products of I, X, Y, Z) as (x, z) bit masks; conjugation by CX gates; commutator closure."""


def cx(p, c, t):
    """Conjugate the string p = (x, z) by CX with control c, target t (qubits 0-based)."""
    x, z = p
    if x >> c & 1:
        x ^= 1 << t
    if z >> t & 1:
        z ^= 1 << c
    return x, z


def ring(p, n, power=1):
    """Conjugation by the ring block U = CX_{n-1,n} ... CX_{1,2} CX_{n,1} (1-based), applied `power` times.
    U P U^dagger: the gate applied first in the circuit (CX_{n,1}) acts last on P."""
    for _ in range(power):
        for c in range(n - 2, -1, -1):  # CX_{n-1,n}, ..., CX_{1,2} in 0-based (c, c+1)
            p = cx(p, c, c + 1)
        p = cx(p, n - 1, 0)  # CX_{n,1}
    return p


def anticommute(p, q):
    return (bin(p[0] & q[1]).count("1") + bin(p[1] & q[0]).count("1")) & 1


def ycount(p):
    return bin(p[0] & p[1]).count("1")


def show(p, n):
    s = ""
    for i in range(n):
        b = (p[0] >> i & 1, p[1] >> i & 1)
        s += {(0, 0): "I", (1, 0): "X", (0, 1): "Z", (1, 1): "Y"}[b]
    return s


def closure(gens):
    """Set of strings spanning the algebra generated by gens under commutators (commutators of strings are strings)."""
    S = list(dict.fromkeys(gens))
    seen = set(S)
    i = 0
    while i < len(S):
        p = S[i]
        for j in range(i):
            q = S[j]
            if anticommute(p, q):
                r = (p[0] ^ q[0], p[1] ^ q[1])
                if r not in seen:
                    seen.add(r)
                    S.append(r)
        i += 1
    return seen


def Y(j):
    return (1 << j, 1 << j)
