"""Numerical checks for the classical lower bound in ../RESULTS.md, Section 10. Exact integer arithmetic.

For query sets X let w_j = (<b_j, delta_s>)_s and w^v = (<B_v, delta_s>)_s. The set Y(X) holds the v with
G w^v outside the lattice L generated by the w_j.

check_y:         |Y| <= 1 + 3/2 (T + 1) for random and structured X, with an explicit e for every v outside Y.
check_injection: on random vectors (x, 1), prod g_q <= |det M| and the map of Lemma 4 is injective by brute force.
check_size:      the reduced solution of Lemma 5 obeys its norm bound.
check_tree:      adaptive trees: on (1^n - e_v, a + e) the tree follows the same path for every v outside Y(path),
                 and a -> a + e is injective on the tried a of one tree.
check_disj:      the gadget of Proposition 8: minimum degree 2 exactly when some i has x_i = y_i = 0.
check_fejer:     sum_a |f(a+1) - f(a)| <= (8/3) eta, and the true J = 2 sup-shift sum obeys Lemma 6 on a box.

Limits: small n and T only. The tree test checks the coupling, not the error probabilities. The size bound of
check_y has force only when 1.5 T + 2.5 < n, and the largest |Y| printed never reaches it, so the constant 3/2 is
not stressed. The check at G = 1 is outside Lemma 4; it is printed for comparison. The degree identities in
check_y and the residual test in check_size hold for any X. The eta tested is far above the eta of Theorem 7.
"""
import itertools
import json
import math
import os
import random
from fractions import Fraction

import numpy as np


def pairs(n):
    return list(itertools.combinations(range(n), 2))


def family(n):
    E = pairs(n)
    idx = {e: i for i, e in enumerate(E)}
    ed = lambda u, v: idx[(min(u, v), max(u, v))]
    basis = []
    for u, v in E:
        if u == 0 or (u, v) == (1, 2):
            continue
        b = [0] * len(E)
        for f, c in ((ed(u, v), 1), (ed(0, u), -1), (ed(0, v), -1), (ed(0, 1), 1), (ed(0, 2), 1), (ed(1, 2), -1)):
            b[f] += c
        basis.append(b)
    Bv = []
    for v in range(n):
        a, c = [w for w in range(n) if w != v][:2]
        b = [0] * len(E)
        b[ed(v, a)] += 1
        b[ed(v, c)] += 1
        b[ed(a, c)] -= 1
        Bv.append(b)
    return E, basis, Bv


def delta(x, E):
    return [x[u] ^ x[v] for u, v in E]


def dot(a, b):
    return sum(p * q for p, q in zip(a, b))


def col_echelon(cols, m):
    """Unimodular column operations on `cols` (lists of length m). Returns pivots [(row, col, combo)]."""
    k = len(cols)
    cols = [list(c) for c in cols]
    combos = [[1 if i == j else 0 for j in range(k)] for i in range(k)]
    piv = []
    used = 0
    for r in range(m):
        while True:
            nz = [j for j in range(used, k) if cols[j][r] != 0]
            if len(nz) <= 1:
                break
            j0 = min(nz, key=lambda j: abs(cols[j][r]))
            for j in nz:
                if j != j0:
                    q = cols[j][r] // cols[j0][r]
                    cols[j] = [a - q * b for a, b in zip(cols[j], cols[j0])]
                    combos[j] = [a - q * b for a, b in zip(combos[j], combos[j0])]
        nz = [j for j in range(used, k) if cols[j][r] != 0]
        if nz:
            j = nz[0]
            cols[used], cols[j] = cols[j], cols[used]
            combos[used], combos[j] = combos[j], combos[used]
            piv.append(r)
            used += 1
    return cols[:used], combos[:used], piv, combos[used:]


def solve_lattice(ech, combos, piv, w):
    """Integer e with sum e_j w_j = w, or None."""
    w = list(w)
    e = [0] * (len(combos[0]) if combos else 0)
    for c, combo, r in zip(ech, combos, piv):
        if w[r] % c[r] != 0:
            return None
        q = w[r] // c[r]
        w = [a - q * b for a, b in zip(w, c)]
        e = [a + q * b for a, b in zip(e, combo)]
    return e if not any(w) else None


def analyse(n, X, G):
    E, basis, Bv = family(n)
    ds = [delta(x, E) for x in X]
    W = [[dot(b, d) for d in ds] for b in basis]  # column j is w_j
    ech, combos, piv, _ = col_echelon(W, len(X))
    Y, sols = [], {}
    for v in range(n):
        w = [G * dot(Bv[v], d) for d in ds]
        e = solve_lattice(ech, combos, piv, w)
        if e is None:
            Y.append(v)
        else:
            sols[v] = e
    return Y, sols, W, E, basis, Bv, ds


def deg(n, E, A):
    d = [0] * n
    for (u, v), a in zip(E, A):
        d[u] += a
        d[v] += a
    return d


def check_y(n, X, G, label=None):
    Y, sols, W, E, basis, Bv, ds = analyse(n, X, G)
    T = len(X)
    assert len(Y) <= 1 + 1.5 * (T + 1), (len(Y), T)
    for v, e in sols.items():
        D = [G * Bv[v][i] - sum(ej * b[i] for ej, b in zip(e, basis)) for i in range(len(E))]
        assert all(dot(D, d) == 0 for d in ds)
        dg = deg(n, E, D)
        assert dg[v] == 2 * G and all(dg[u] == 0 for u in range(n) if u != v)
    return len(Y)


def rank_frac(rows):
    rows = [[Fraction(x) for x in r] for r in rows]
    rk, piv = 0, []
    ncol = len(rows[0]) if rows else 0
    for c in range(ncol):
        p = next((i for i in range(rk, len(rows)) if rows[i][c] != 0), None)
        if p is None:
            continue
        rows[rk], rows[p] = rows[p], rows[rk]
        rows[rk] = [x / rows[rk][c] for x in rows[rk]]
        for i in range(len(rows)):
            if i != rk and rows[i][c] != 0:
                f = rows[i][c]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[rk])]
        piv.append(c)
        rk += 1
    return rk, piv, rows[:rk]


def det_frac(M):
    M = [[Fraction(x) for x in r] for r in M]
    d = Fraction(1)
    for c in range(len(M)):
        p = next((i for i in range(c, len(M)) if M[i][c] != 0), None)
        if p is None:
            return Fraction(0)
        if p != c:
            M[c], M[p] = M[p], M[c]
            d = -d
        d *= M[c][c]
        for i in range(c + 1, len(M)):
            f = M[i][c] / M[c][c]
            M[i] = [a - f * b for a, b in zip(M[i], M[c])]
    return d


def check_injection(trials, rng):
    """Lemma 4 on r random columns (x, 1): g_q > 0 on Q, prod g_q <= |det M|, and z -> M'z + M Z^rho injective."""
    tested = large = 0
    for _ in range(trials):
        m, r = rng.randint(2, 5), rng.randint(3, 8)
        cols = [[rng.randint(0, 1) for _ in range(m)] + [1] for _ in range(r)]
        kern = col_echelon(cols, m + 1)[3]
        rho = r - len(kern)
        if not kern:
            continue
        P = rank_frac([[c[i] for c in cols] for i in range(m + 1)])[1]
        rows = rank_frac(cols)[1]
        Q = [q for q in range(r) if q not in P]
        M = [[cols[j][i] for j in P] for i in rows]
        Mp = [[cols[q][i] for q in Q] for i in rows]
        d = abs(det_frac(M))
        g = {q: math.gcd(*[k[q] for k in kern]) for q in Q}
        assert d != 0 and all(g[q] > 0 for q in Q)
        prod = math.prod(g.values())
        assert prod <= d, (prod, d)
        seen = set()
        for z in itertools.product(*[range(g[q]) for q in Q]):
            v = [Fraction(sum(row[k] * z[k] for k in range(len(Q)))) for row in Mp]
            A = rank_frac([row + [t] for row, t in zip(M, v)])[2]
            cl = tuple(row[-1] % 1 for row in A)
            assert cl not in seen, (cols, z)
            seen.add(cl)
        tested += 1
        large += prod > 1
    assert large > 0
    return tested, large


def check_size(n, X, G):
    """Lemma 5: reduce an integer solution using Cramer kernel vectors; compare with the stated bound."""
    Y, sols, W, E, basis, Bv, ds = analyse(n, X, G)
    T, J = len(X), len(basis)
    if not sols:
        return 0.0
    rows = [[W[j][s] for j in range(J)] for s in range(T)]
    rho, piv, rref = rank_frac(rows)
    if rho == 0:
        return 0.0
    free = [j for j in range(J) if j not in piv]
    worst = 0.0
    for v, e0 in sols.items():
        target = [G * dot(Bv[v], d) for d in ds]
        # e' supported on pivots, from the reduced system
        aug = rank_frac([r + [t] for r, t in zip(rows, target)])[2]
        ep = [Fraction(0)] * J
        for r in aug:
            lead = next(c for c, x in enumerate(r) if x != 0)
            ep[lead] = r[-1]
        # r_q = e0_q on the free coordinates, in units of the kernel vector with q-entry 1
        kern = {}
        den = 1
        for q in free:
            k = [Fraction(0)] * J
            k[q] = Fraction(1)
            for i, p in enumerate(piv):
                k[p] = -rref[i][q]
            kern[q] = k
            den = math.lcm(den, *[x.denominator for x in k])
        e = list(e0)
        for q in free:
            kk = [int(x * den) for x in kern[q]]  # integer kernel vector with q-entry den
            s = e[q] // den
            e = [a - s * b for a, b in zip(e, kk)]
        assert [sum(e[j] * W[j][s] for j in range(J)) for s in range(T)] == target
        l1 = sum(abs(x) for x in e)
        ch = (6 * math.sqrt(rho)) ** rho
        bound = rho * 2 * G * ch + J * (rho + 1) * ch
        worst = max(worst, l1 / bound)
    assert worst <= 1 + 1e-9, worst
    return worst


def check_tree(n, T, G, trials, rng):
    """Random adaptive tree: the next set is a hash of the answers so far."""
    E, basis, Bv = family(n)
    J = len(basis)
    W0 = 10 ** 6
    seen = 0
    for trial in range(trials // 4):
        salt = rng.getrandbits(32)
        def next_set(ans):
            r = random.Random(hash((salt, tuple(ans))))
            return [r.randint(0, 1) if r.random() < 0.7 else 0 for _ in range(n)]
        def run(A):
            ans, xs = [], []
            for _ in range(T):
                x = next_set(ans)
                xs.append(x)
                ans.append(dot(A, delta(x, E)))
            return xs, ans
        images = {}
        for _ in range(16):
            a = [rng.randint(-1, 1) for _ in range(J)]
            A1 = [W0 + G * sum(B[i] for B in Bv) + sum(ai * b[i] for ai, b in zip(a, basis)) for i in range(len(E))]
            xs, ans = run(A1)
            Y, sols, *_ = analyse(n, xs, G)
            assert len(Y) <= 1 + 1.5 * (T + 1)
            for v, e in sols.items():
                a2 = [ai + ei for ai, ei in zip(a, e)]
                A2 = [W0 + G * sum(B[i] for u, B in enumerate(Bv) if u != v)
                      + sum(ai * b[i] for ai, b in zip(a2, basis)) for i in range(len(E))]
                d2 = deg(n, E, A2)
                d1 = deg(n, E, A1)
                assert d2[v] == d1[v] - 2 * G and all(d2[u] == d1[u] for u in range(n) if u != v)
                xs2, ans2 = run(A2)
                assert xs2 == xs and ans2 == ans
                assert images.setdefault((v, tuple(a2)), tuple(a)) == tuple(a)
                seen += 1
    return seen


def check_disj(trials, rng):
    hubs = ["A1", "A2", "B1", "B2", "H1", "H2", "H3"]
    for _ in range(trials):
        k = rng.randint(1, 10)
        x = [rng.randint(0, 1) for _ in range(k)]
        y = [rng.randint(0, 1) for _ in range(k)]
        E = {frozenset(p) for p in itertools.combinations(hubs, 2)}
        for i in range(k):
            E |= {frozenset((i, "A1")), frozenset((i, "B1"))}
            if x[i]:
                E.add(frozenset((i, "A2")))
            if y[i]:
                E.add(frozenset((i, "B2")))
        dmin = min(sum(v in e for e in E) for v in list(range(k)) + hubs)
        assert dmin >= 2 and (dmin == 2) == any(a == 0 and b == 0 for a, b in zip(x, y))


def check_fejer():
    def f(a, eta):
        if a == 0:
            return eta
        return math.sin(math.pi * eta * a) ** 2 / (math.pi ** 2 * eta * a * a)
    for eta in (0.5, 0.2, 0.05, 0.01):
        L = int(200 / eta)
        tv = sum(abs(f(a + 1, eta) - f(a, eta)) for a in range(-L, L))
        assert tv <= (8 / 3) * eta, (eta, tv)
        print(f"fejer eta={eta}: sum |f(a+1)-f(a)| / eta = {tv / eta:.4f}, bound 8/3 = {8 / 3:.4f}", flush=True)
    for eta, E_, B in ((0.05, 2, 1200), (0.02, 3, 1500), (0.2, 1, 800)):
        xs = np.arange(-B - 2 * E_, B + 2 * E_ + 1, dtype=float)
        F = np.array([f(int(a), eta) for a in xs])
        win = np.lib.stride_tricks.sliding_window_view(F, 2 * E_ + 1)
        hi, lo, mid = win.max(axis=1), win.min(axis=1), F[E_:-E_]
        P = np.outer(mid, mid)
        sup = np.maximum(np.outer(hi, hi) - P, P - np.outer(lo, lo)).sum()
        bound = 12 * E_ * eta * math.exp(12 * E_ * eta)
        assert sup <= bound, (eta, E_, sup, bound)
        print(f"shift J=2 eta={eta} E={E_}: sup sum / bound = {sup / bound:.3f}", flush=True)


