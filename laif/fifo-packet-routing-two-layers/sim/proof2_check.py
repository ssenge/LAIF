"""Numerical checks for the README (two-layer FIFO packet routing game, UFR equilibria).

Every check_* function tests one lemma of the README with asserts, in exact arithmetic (Fraction) wherever real numbers
appear. Equilibria are generated by the sequential best response of Lemma 2 with every tie choice (exhaustive on small
instances) or with greedy / least-queue / random ties (larger instances); check_lemma2 confirms on tiny instances that
these are exactly the UFR states (brute force over all states with pr.is_ufr).

Run: python proof2_check.py [seed]   (single core, a few minutes)."""
import itertools
import random
import sys
from fractions import Fraction as Fr

from pr import greedy, is_ufr, load, opt, opt_flow

# ----------------------------------------------------------------------------- notation of the README


def Phi(b, y):
    return sum(max(0, y - f) for f in b)


def N(b, y):
    return sum(1 for f in b if f < y)


def mu(b, B):
    """max integer x >= b_1 with Phi(x) <= B"""
    x = min(b)
    while Phi(b, x + 1) <= B:
        x += 1
    return x


def nu(b, B):
    """inverse of Phi on [b_1, oo) (piecewise linear)"""
    m = mu(b, B)
    return m + Fr(B - Phi(b, m), N(b, m + 1))


def g(b, x):
    th = mu(b, x)
    return min(x - N(b, th), Phi(b, th))


def Phik(b, k, y):
    return sum(max(0, y - f) for f in sorted(b)[:k])


def Psik(b, k, B):
    return Phik(b, k, nu(b, B))


def F(a, b, T):
    A, Bs = sorted(a), sorted(b)
    return sum(max(0, T + 1 - A[p] - Bs[p]) for p in range(min(len(a), len(b))))


def cut(a, b, T, y):
    return sum(max(0, y + 1 - x) for x in a) + sum(max(0, T - y - f) for f in b)


# ----------------------------------------------------------------------------- sequential best response (Lemma 2)


def seq_all(a, b, n, cap=None):
    """All states of the sequential best response, every tie choice in both layers. Yields paths [(e, f)]."""
    out = []

    def rec(i, cnt, last, paths):
        if cap is not None and len(out) >= cap:
            return
        if i == n:
            out.append(list(paths))
            return
        v1 = [cnt[e] + a[e] for e in range(len(a))]
        al = min(v1)
        for e in [e for e in range(len(a)) if v1[e] == al]:
            lat = [max(al, last[f] + 1) + b[f] for f in range(len(b))]
            mn = min(lat)
            for f in [f for f in range(len(b)) if lat[f] == mn]:
                c2 = list(cnt); c2[e] += 1
                l2 = list(last); l2[f] = max(al, last[f] + 1)
                paths.append((e, f)); rec(i + 1, c2, l2, paths); paths.pop()

    rec(0, [0] * len(a), [-1] * len(b), [])
    return out


def seq_one(a, b, n, rng, mode):
    """One state; mode 0 random ties, 1 greedy (longest queue), 2 shortest queue."""
    cnt, last, paths = [0] * len(a), [-1] * len(b), []
    for i in range(n):
        v1 = [cnt[e] + a[e] for e in range(len(a))]
        al = min(v1)
        e = rng.choice([e for e in range(len(a)) if v1[e] == al])
        lat = [max(al, last[f] + 1) + b[f] for f in range(len(b))]
        mn = min(lat)
        ties = [f for f in range(len(b)) if lat[f] == mn]
        f = rng.choice(ties) if mode == 0 else (max if mode == 1 else min)(ties, key=lambda f: (last[f], -f))
        cnt[e] += 1; last[f] = max(al, last[f] + 1); paths.append((e, f))
    return paths


def trajectory(a, b, paths):
    """alpha (v1), d (layer-2 departure), beta (d-arrival) of every player, by FIFO loading in index order."""
    n = len(paths)
    cnt, last = [0] * len(a), [-1] * len(b)
    al, d, be = [0] * n, [0] * n, [0] * n
    for i in range(n):
        e, f = paths[i]
        al[i] = cnt[e] + a[e]; cnt[e] += 1
    for i in sorted(range(n), key=lambda i: (al[i], i)):
        f = paths[i][1]
        d[i] = max(al[i], last[f] + 1); last[f] = d[i]; be[i] = d[i] + b[f]
    return al, d, be


# ----------------------------------------------------------------------------- instance generators


def gen(rng):
    TM = rng.choice([2, 3, 5, 8, 20])
    if rng.random() < 0.5:
        a = [rng.randint(1, TM) for _ in range(rng.randint(1, 7))]
        b = [rng.randint(1, TM) for _ in range(rng.randint(1, 7))]
    else:  # repeated values: the extremal instances have many equal edges
        a = sum(([rng.randint(1, TM)] * rng.randint(1, 6) for _ in range(rng.randint(1, 3))), [])
        b = sum(([rng.randint(1, TM)] * rng.randint(1, 6) for _ in range(rng.randint(1, 3))), [])
    return a, b, rng.randint(2, 100)


def gen_small(rng):
    a = [rng.randint(1, 4) for _ in range(rng.randint(1, 4))]
    b = [rng.randint(1, 4) for _ in range(rng.randint(1, 4))]
    return a, b, rng.randint(2, 9)


def family(j):
    """3C = 4T* + 1: a = 1^(2j+1), b = 1^j (2j)^(j+1), n = 4j^2 - 2j - 1, C = 4j - 1, T* = 3j - 1."""
    return [1] * (2 * j + 1), [1] * j + [2 * j] * (j + 1), 4 * j * j - 2 * j - 1


# ----------------------------------------------------------------------------- checks


def check_lemma1(rng, iters):
    """Cut bound: cut(y) >= F(T) for all y, = F(T) on the explicit interval I; T* = min{T: F(T) >= n}."""
    for _ in range(iters):
        a, b, n = gen_small(rng) if rng.random() < 0.5 else gen(rng)
        A, Bs, K = sorted(a), sorted(b), min(len(a), len(b))
        for T in range(0, 2 * (A[0] + Bs[0]) + 12):
            FT = F(a, b, T)
            assert all(cut(a, b, T, y) >= FT for y in range(-3, T + 3))
            k = sum(1 for p in range(K) if A[p] + Bs[p] <= T)
            INF = 10 ** 9
            ak = A[k - 1] if k >= 1 else -INF
            bk = Bs[k - 1] if k >= 1 else -INF
            a1 = A[k] if k < len(A) else INF
            b1 = Bs[k] if k < len(Bs) else INF
            lo, hi = max(ak - 1, T - b1), min(T - bk, a1 - 1)
            assert lo <= hi, (a, b, T)
            y = max(lo, -5) if hi >= -5 else lo
            y = min(y, hi)
            assert cut(a, b, T, y) == FT, (a, b, T, y)
        T = 0
        while F(a, b, T) < n:
            T += 1
        assert T == opt([a, b], n)
        if n <= 9 and len(a) + len(b) <= 7:
            assert opt([a, b], n) == opt_flow([a, b], n)
    print("lemma 1 (cut bound, explicit min cut, OPT formula) ok")


def check_lemma2(rng, iters):
    """UFR states = sequential best response states (both directions), on tiny instances; arrival structure."""
    for _ in range(iters):
        a = [rng.randint(1, 3) for _ in range(rng.randint(1, 3))]
        b = [rng.randint(1, 3) for _ in range(rng.randint(1, 2 if len(a) == 3 else 3))]
        n = rng.randint(1, 4 if len(a) * len(b) <= 4 else 3)
        P = list(itertools.product(range(len(a)), range(len(b))))
        U = {S for S in itertools.product(P, repeat=n) if is_ufr([a, b], list(S))}
        Sq = {tuple(p) for p in seq_all(a, b, n)}
        assert U == Sq, (a, b, n)
    for _ in range(iters * 5):
        a, b, n = gen(rng)
        paths = seq_one(a, b, n, rng, rng.randrange(3))
        al, d, be = trajectory(a, b, paths)
        assert load([a, b], paths) == be
        assert al == sorted(al) and be == sorted(be)                       # (a), (c)
        assert al == sorted(x + q for x in a for q in range(n))[:n]         # (d)
        ts = al[-1]
        for t in range(ts):
            assert al.count(t) == sum(1 for x in a if x <= t)
        R = al[:-1].count(ts)
        assert 0 <= R <= sum(1 for x in a if x <= ts) - 1 and ts >= min(a)
    print("lemma 2 (UFR = sequential best response; arrivals at v1) ok")


def check_lemmas34(a, b, paths):
    """Contiguity, levels, invariant h <= mu+1, Phi(mu) <= B < Phi(mu+1), departures >= max(N(th), x - Phi(th))."""
    n = len(paths)
    al, d, be = trajectory(a, b, paths)
    fs = [p[1] for p in paths]
    for i in range(n):
        t = al[i]
        q = [0] * len(b)
        for f in range(len(b)):
            deps = sorted(d[j] for j in range(i) if fs[j] == f and d[j] >= t)
            assert deps == list(range(t, t + len(deps)))                    # Lemma 3 contiguity
            q[f] = len(deps)
        h = [b[f] + q[f] for f in range(len(b))]
        m0 = min(h)
        assert be[i] == t + m0 and h[fs[i]] == m0                           # latency = min level
        assert all(h[f] <= m0 + 1 for f in range(len(b)) if q[f] > 0)      # Lemma 4 (a)
        B = sum(q)
        assert Phi(b, m0) <= B < Phi(b, m0 + 1) and mu(b, B) == m0          # Lemma 4 (b)
    ts = al[-1]
    Bt = lambda t: sum(1 for j in range(n) if al[j] < t and d[j] >= t)
    for t in range(ts):
        x = Bt(t) + al.count(t)
        th = mu(b, x)
        m = sum(1 for j in range(n) if d[j] == t)
        assert m >= max(N(b, th), x - Phi(b, th))                           # Lemma 4 (c)
        assert Bt(t + 1) == x - m <= g(b, x)
    Q = sum(1 for j in range(n - 1) if d[j] >= ts)
    R = al[:-1].count(ts)
    assert Q == Bt(ts) + R and be[-1] - ts == mu(b, Q)


def worst_process(a, b, n):
    """B-hat of Lemma 5: returns ts, c_t list, R, Bhat list, Lhat, Chat."""
    al = sorted(x + q for x in a for q in range(n))[:n]
    ts = al[-1]
    cs = [sum(1 for x in a if x <= t) for t in range(ts)]
    R = n - 1 - sum(cs)
    Bh = [0]
    for t in range(ts):
        Bh.append(g(b, Bh[-1] + cs[t]))
    Lh = mu(b, Bh[-1] + R)
    return ts, cs, R, Bh, Lh, ts + Lh


def check_lemma5(rng, iters):
    """g nondecreasing; actual backlog <= B-hat at every step start; L <= L-hat."""
    for _ in range(iters):
        b = [rng.randint(1, rng.choice([2, 4, 9])) for _ in range(rng.randint(1, 7))]
        vals = [g(b, x) for x in range(0, 80)]
        assert all(vals[x] <= vals[x + 1] for x in range(len(vals) - 1)), b
        assert all(Phi(b, mu(b, x) - 1) <= vals[x] <= Phi(b, mu(b, x)) for x in range(80))
    print("lemma 5 (g nondecreasing) ok")


def compare_hat(a, b, paths):
    n = len(paths)
    al, d, be = trajectory(a, b, paths)
    ts, cs, R, Bh, Lh, Ch = worst_process(a, b, n)
    for t in range(ts + 1):
        assert sum(1 for j in range(n) if al[j] < t and d[j] >= t) <= Bh[t]
    assert be[-1] <= Ch
    return be[-1], Ch


def check_lemma6(rng, iters):
    """One-step inequality Psi_k(B') - Psi_k(B) <= (c-k)^+ + (k/4)(1 + nu(B') - nu(B)), B' = g(B+c), exact."""
    worst = None
    for _ in range(iters):
        b = [rng.randint(1, rng.choice([2, 3, 5, 9])) for _ in range(rng.randint(1, 8))]
        B, c = rng.randint(0, 60), rng.randint(0, 14)
        B2 = g(b, B + c)
        assert nu(b, B2) <= mu(b, B + c) and nu(b, B2) + 1 >= nu(b, B + c)   # facts (i), (ii)
        for k in range(1, len(b) + 1):
            s = max(0, c - k) + Fr(k, 4) * (1 + nu(b, B2) - nu(b, B)) - (Psik(b, k, B2) - Psik(b, k, B))
            assert s >= 0, (b, B, c, k)
            worst = s if worst is None else min(worst, s)
        # Psi_k has slope <= 1
        for k in range(1, len(b) + 1):
            assert Psik(b, k, B + 1) - Psik(b, k, B) <= 1
    print("lemma 6 (one-step inequality) ok, min slack", worst)


def key_bound(a, b, n):
    """Lemma 7 for every k; and the chain of the theorem. Returns (Chat, T*)."""
    A, Bs = sorted(a), sorted(b)
    ts, cs, R, Bh, Lh, Ch = worst_process(a, b, n)
    sig = A[0] + Bs[0]
    for k in range(1, len(b) + 1):
        E = sum(max(0, c - k) for c in cs)
        assert Phik(b, k, Lh) <= E + R + Fr(k, 4) * (Ch - sig), (a, b, n, k)
    Mp = Fr(3 * Ch + sig, 4)
    for k in range(0, min(len(a), len(b)) + 1):
        assert sum(Mp - A[p] - Bs[p] for p in range(k)) <= n - 1
    T = opt([a, b], n)
    assert F(a, b, int(Mp) - 1) <= n - 1 and T >= int(Mp)
    return Ch, T


def check_theorem(rng, iters_small, iters_big):
    """T* >= floor((3C + a1 + b1)/4) for all states; hence 3C <= 4T* + 1 and C/T* <= 7/5."""
    best = Fr(0)
    for _ in range(iters_small):
        a, b, n = gen_small(rng)
        Ch, T = key_bound(a, b, n)
        for p in seq_all(a, b, n, cap=3000):
            check_lemmas34(a, b, p)
            C, _ = compare_hat(a, b, p)
            assert 4 * T >= 3 * C + min(a) + min(b) - 3 and 3 * C <= 4 * T + 1 and (T > 2 or C == 2)
            best = max(best, Fr(C, T))
    for _ in range(iters_big):
        a, b, n = gen(rng)
        Ch, T = key_bound(a, b, n)
        for mode in range(3):
            p = seq_one(a, b, n, rng, mode)
            if n <= 40:
                check_lemmas34(a, b, p)
            C, _ = compare_hat(a, b, p)
            assert 4 * T >= 3 * C + min(a) + min(b) - 3 and 3 * C <= 4 * T + 1 and (T > 2 or C == 2)
            best = max(best, Fr(C, T))
    assert best <= Fr(7, 5)
    print("lemmas 3, 4, 7 and theorem ok; max C/T* seen", best)


def check_family(jmax):
    """The tight family: worst UFR makespan 4j-1, OPT 3j-1, so 3C = 4T* + 1; j = 2 gives C/T* = 7/5."""
    for j in range(2, jmax + 1):
        a, b, n = family(j)
        p, arr = greedy([a, b], n)
        C, T = max(arr), opt([a, b], n)
        assert (C, T) == (4 * j - 1, 3 * j - 1) and 3 * C == 4 * T + 1
        assert worst_process(a, b, n)[5] == C          # the greedy state attains C-hat
        if j <= 3:
            assert is_ufr([a, b], p)
            assert opt_flow([a, b], n) == T
    print("tight family j = 2 ..", jmax, "ok (j = 2: a = 1^5, b = 1,1,4,4,4, n = 11, C = 7, T* = 5)")


