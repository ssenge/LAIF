"""Target family psi_L (even L >= 4): pseudospins k_j = (2j-1) pi/L at +X for j < L/2 and at -X for k* = (L-1) pi/L.
(1) Depth L/2 + 1 preparations, found numerically (residual asserted < 1e-12), for L = 4..10.
(2) The physical state of such a preparation equals, up to phase, sum_{i<j} sin(pi (j-i)/L) |-_i -_j> in the X basis
    (normalized, all other sites +), asserted to 1e-9 on 2^L amplitudes.
(3) Rigidity (Theorem 1): at depth p = L/2 the all-pi circuit (every SO(3) angle pi) maps every pseudospin to -X, and
    random depth-p circuits never bring pseudospin k* closer than pi - 2 p pi/L to -X (asserted on samples).
(4) The algebra of infinitesimal rotations generated by the two layer generators on the pseudospins has dimension 3L/2 (all of it) for L <= 24 (double precision)."""
import itertools, numpy as np
from scipy.optimize import least_squares
from reduce import chain, vqcs
def rot(ax, a):
    x, y, z = ax; c, s = np.cos(a), np.sin(a); K = np.array([[0, -z, y], [z, 0, -x], [-y, x, 0]]); return np.eye(3) + s * K + (1 - c) * K @ K
def W(g, b, KS):
    out = []
    for k in KS:
        n = (np.cos(k), 0, np.sin(k)); w = np.array([1., 0, 0])
        for gj, bj in zip(g, b): w = rot((1, 0, 0), 4 * bj) @ (rot(n, 4 * gj) @ w)
        out.append(w)
    return np.array(out)
def target(L): return np.array([[1., 0, 0]] * (L // 2 - 1) + [[-1., 0, 0]])
def closed_form(L):
    v = np.zeros(2 ** L)
    for i, j in itertools.combinations(range(L), 2):
        v[(1 << (L - 1 - i)) | (1 << (L - 1 - j))] = np.sin(np.pi * (j - i) / L)
    return v / np.linalg.norm(v)
if __name__ == "__main__":
    Hd = np.array([[1, 1], [1, -1]]) / np.sqrt(2)
    for L in [4, 6, 8, 10]:
        KS = [(2 * j - 1) * np.pi / L for j in range(1, L // 2 + 1)]; p = L // 2 + 1; rng = np.random.default_rng(L)
        for _ in range(500):
            r = least_squares(lambda th: (W(th[:p], list(th[p:]) + [0.], KS) - target(L)).ravel(), rng.uniform(0, np.pi / 2, 2 * p - 1), xtol=1e-15, ftol=1e-15, gtol=1e-15)
            if r.cost < 1e-26: break
        assert r.cost < 1e-26, L
        g, b = r.x[:p], list(r.x[p:]) + [0.]
        HH = Hd
        for _ in range(L - 1): HH = np.kron(HH, Hd)
        c = HH @ vqcs(L, g, b, chain(L)); ov = abs(np.vdot(closed_form(L), c))
        assert ov > 1 - 1e-9, (L, ov)
        print(f"L={L}: depth {p} preparation, residual {np.sqrt(2 * r.cost):.1e}, |<closed form|state>| = {ov:.12f}")
        print("   angles gamma =", np.round(np.mod(g, np.pi / 2), 9), " beta =", np.round(np.mod(b, np.pi / 2), 9))
    for L in range(4, 31, 2):
        KS = [(2 * j - 1) * np.pi / L for j in range(1, L // 2 + 1)]; p = L // 2; a = np.pi / L; rng = np.random.default_rng(1)
        assert np.allclose(W([np.pi / 4] * p, [np.pi / 4] * p, KS), [[-1, 0, 0]] * (L // 2), atol=1e-9)
        for _ in range(300):
            w = W(rng.uniform(0, np.pi / 2, p), rng.uniform(0, np.pi / 2, p), KS)[-1]
            assert np.arccos(np.clip(-w[0], -1, 1)) >= np.pi - 2 * p * a - 1e-9
    print("rigidity checks passed for L = 4..30")
    for L in range(4, 25, 2):
        m = L // 2; KS = [(2 * j - 1) * np.pi / L for j in range(1, m + 1)]
        P = [np.array([[0, 0, 0], [0, 0, -1], [0, 1, 0]]), np.array([[0, 0, 1], [0, 0, 0], [-1, 0, 0]]), np.array([[0, -1, 0], [1, 0, 0], [0, 0, 0]])]
        def blk(cs):                                   # element of sum of so(3): per-pseudospin coefficient vectors
            M = np.zeros((3 * m, 3 * m))
            for i, cv in enumerate(cs): M[3 * i:3 * i + 3, 3 * i:3 * i + 3] = sum(c * Pk for c, Pk in zip(cv, P))
            return M
        A = blk([(1, 0, 0)] * m); B = blk([(np.cos(k), 0, np.sin(k)) for k in KS])
        basis = []; frontier = [A, B]
        def add(M):
            v = M.ravel(); Q = np.array(basis) if basis else np.zeros((0, v.size))
            if Q.size: v = v - Q.T @ (Q @ v)
            nv = np.linalg.norm(v)
            if nv > 1e-8: basis.append(v / nv); return True
            return False
        for M in frontier: add(M)
        while frontier:
            new = []
            for M in frontier:
                for N in (A, B):
                    Cm = M @ N - N @ M
                    if add(Cm): new.append(Cm)
            frontier = new
        assert len(basis) == 3 * m, (L, len(basis))
    print("generated algebra has dimension 3L/2 for L = 4..24")
