"""Checks for the note on RY layers with a CX ring (README.md).

0. The convention: dense matrices U = CX_{n-1,n} ... CX_{1,2} CX_{n,1} and U^dagger Y_j U reproduce the orbits of [1]
   for n = 3 and agree with the string arithmetic for n = 3, 4, 5.
1. The closed forms of Ad_U(Y_j) and of the inverse map on single-qubit X and Z, for 3 <= n <= 40.
2. The base case: on Q_4 = {1, 2, 3, 4, n}, the algebra generated by Y_1..Y_4, Y_n, s_1, s_2, s_3 contains every odd
   string that commutes with K_4, except the elements of K_4, and nothing else (also Q_5).
3. The group K of Y-type strings commuting with Y_j and s_1..s_{n-2} (4 elements), and the layer criterion: the number
   of layers L for which some J in K other than I commutes with all of Ad_U^k(Y_j), k < L, for 5 <= n <= 60.
4. Direct commutator closure for 2 <= n <= 8: dim g_L for each L, dim g = 2^(n-1)(2^n - 1), and the saturation depth.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pauli import Y, anticommute, cx, ring

POP = np.array([bin(i).count("1") & 1 for i in range(1 << 16)], dtype=np.uint8)


def par(a):  # parity of the bits of a uint64 array
    a = a ^ (a >> np.uint64(32))
    a = a ^ (a >> np.uint64(16))
    return POP[(a & np.uint64(0xFFFF)).astype(np.int64)]


def closure(gens):
    """All strings in the algebra generated by gens under commutators (vectorised over the current list)."""
    X = [p[0] for p in dict.fromkeys(gens)]
    Z = [p[1] for p in dict.fromkeys(gens)]
    seen = set(zip(X, Z))
    xs, zs = np.array(X, dtype=np.uint64), np.array(Z, dtype=np.uint64)
    i = 0
    while i < len(xs):
        x, z = xs[i], zs[i]
        m = par((xs[:i] & z) ^ (zs[:i] & x)).astype(bool)
        nx, nz = xs[:i][m] ^ x, zs[:i][m] ^ z
        new = [(a, b) for a, b in zip(nx.tolist(), nz.tolist()) if (a, b) not in seen]
        if new:
            seen.update(new)
            xs = np.concatenate([xs, np.array([a for a, _ in new], dtype=np.uint64)])
            zs = np.concatenate([zs, np.array([b for _, b in new], dtype=np.uint64)])
        i += 1
    return seen


def P(s):
    return (sum(1 << i for i, c in enumerate(s) if c in "XY"), sum(1 << i for i, c in enumerate(s) if c in "ZY"))


def inv(p, n):
    """Ad_U^{-1}: the gates of the ring in circuit order, CX_{n,1} first."""
    p = cx(p, n - 1, 0)
    for c in range(n - 1):
        p = cx(p, c, c + 1)
    return p


def s(j, n):  # Ad_U(Y_j), 1 <= j <= n - 2
    return P("Z" * (j - 1) + "YX" + "I" * (n - j - 2) + "Z")


def check_matrices():
    I2, X1 = np.eye(2), np.array([[0, 1], [1, 0]])
    Y1, Z1 = np.array([[0, -1j], [1j, 0]]), np.diag([1.0, -1.0])
    mats = {"I": I2, "X": X1, "Y": Y1, "Z": Z1}

    def kron(word):
        out = np.array([[1.0 + 0j]])
        for c in word:
            out = np.kron(out, mats[c])
        return out

    def cxm(c, t, n):  # control c, target t (0-based); qubit 0 is the leftmost tensor factor
        P0, P1 = np.diag([1.0, 0]), np.diag([0, 1.0])
        a = [I2] * n; a[c] = P0
        b = [I2] * n; b[c] = P1; b[t] = X1
        k = lambda fs: np.array([[1.0 + 0j]]) if not fs else np.kron(fs[0], k(fs[1:]))
        return k(a) + k(b)

    def same(A, B):  # equal up to a phase
        z = np.vdot(B.ravel(), A.ravel()) / np.vdot(B.ravel(), B.ravel())
        return abs(abs(z) - 1) < 1e-9 and np.allclose(A, z * B)

    for n in (3, 4, 5):
        U = cxm(n - 1, 0, n)
        for c in range(n - 1):
            U = cxm(c, c + 1, n) @ U
        for j in range(n):
            A = U.conj().T @ kron("I" * j + "Y" + "I" * (n - j - 1)) @ U
            x, z = ring(Y(j), n)
            w = "".join({(0, 0): "I", (1, 0): "X", (0, 1): "Z", (1, 1): "Y"}[(x >> i & 1, z >> i & 1)] for i in range(n))
            assert same(A, kron(w))
            if n == 3:
                assert w == ["YXZ", "YYY", "YZX"][j]  # [1]: Y1 -> Y1X2Z3, Y2 -> -Y1Y2Y3, Y3 -> Y1Z2X3
    print("0. dense matrices U^dagger Y_j U match [1] for n = 3 and the string arithmetic for n = 3, 4, 5")


def check_formulas():
    for n in range(3, 41):
        for j in range(1, n - 1):
            assert ring(Y(j - 1), n) == s(j, n)
        assert ring(Y(n - 2), n) == P("Y" + "Z" * (n - 3) + "YY")
        assert ring(Y(n - 1), n) == P("Y" + "Z" * (n - 2) + "X")
        for i in range(n):
            assert inv(ring((1 << i, 0), n), n) == (1 << i, 0)
            xs = P("I" * i + "X" * (n - i)) if 0 < i < n - 1 else P("X" * n) if i == 0 else None
            if i == n - 1:
                xs = P("X" * (n - 1) + "I")
            assert inv((1 << i, 0), n) == xs
            zs = P("Z" + "I" * (n - 3) + "ZZ") if i == 0 else P("I" * (i - 1) + "ZZ" + "I" * (n - i - 1))
            assert inv((0, 1 << i), n) == zs
    print("1. closed forms of Ad_U(Y_j) and of the inverse on X_i, Z_i hold for 3 <= n <= 40")


def ypattern(a1, a2, n):
    a = [a1, a2]
    while len(a) < n - 1:
        a.append(a[-2] ^ a[-1])
    a = a[:n - 1] + [a2]
    v = sum(1 << i for i, b in enumerate(a) if b)
    return v, v


def odd(p):
    return bin(p[0] & p[1]).count("1") & 1


def check_base():
    for m in [4, 5]:
        q = m + 1  # qubits 1..m, n -> positions 0..m-1, m
        gens = [Y(k) for k in range(q)] + [P("Z" * (j - 1) + "YX" + "I" * (m - j - 1) + "Z") for j in range(1, m)]
        S = closure(gens)
        K = [ypattern(a1, a2, q) for a1 in (0, 1) for a2 in (0, 1)]
        for g in gens:  # K_m commutes with the generators
            assert all(not anticommute(g, J) for J in K)
        target = {(x, z) for x in range(1 << q) for z in range(1 << q)
                  if odd((x, z)) and all(not anticommute((x, z), J) for J in K) and (x, z) not in K}
        assert S == target, (len(S), len(target))
        print(f"2. Q_{m}: the generated algebra contains all {len(target)} odd strings commuting with K_{m}, outside K_{m}"
              f" ({len(S)} strings in all)")


def layers_needed(n, Lmax=8):
    """Smallest L such that no J in K other than I commutes with every Ad_U^k(Y_j), k < L."""
    K = [ypattern(a1, a2, n) for a1 in (0, 1) for a2 in (0, 1)]
    for j in range(1, n - 1):  # K commutes with the local generators
        assert all(not anticommute(s(j, n), J) for J in K)
    for L in range(1, Lmax + 1):
        alive = []
        for J in K[1:]:
            ok = True
            p = J
            for _ in range(L):  # J commutes with Ad^k(Y_j) for all j iff Ad^{-k}(J) is Y-type
                if p[0] != p[1]:
                    ok = False
                    break
                p = inv(p, n)
            if ok:
                alive.append(J)
        if not alive:
            return L
    return None


def check_criterion():
    for n in range(5, 61):
        L = layers_needed(n)
        assert L == (4 if n % 3 == 0 else 2), (n, L)
    print("3. the layer criterion gives 2 for 3 not dividing n and 4 for 3 dividing n, 5 <= n <= 60")


def check_closure():
    print("4. direct closure: n, dim g_1..g_5, dim so(2^n), saturation depth")
    for n in range(2, 9):
        dims = []
        gens = [Y(k) for k in range(n)]
        layer = gens[:]
        for L in range(1, 6):
            dims.append(len(closure(gens)))
            layer = [ring(p, n) for p in layer]
            gens = gens + layer
        full = 2 ** (n - 1) * (2 ** n - 1)
        assert dims[-1] == full
        Llie = dims.index(full) + 1
        assert Llie == (4 if n % 3 == 0 else 2)
        print(f"   n={n}: {dims}  {full}  depth={Llie}", flush=True)


if __name__ == "__main__":
    check_matrices()
    check_formulas()
    check_base()
    check_criterion()
    check_closure()
    print("all checks passed")
