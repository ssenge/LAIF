"""Exact (5, 4) instance for Lean: five vectors psi_i in Q(i)^3, a witness Y, and for each j an exact factorization
mask_j(Y) = L_j diag(d_j) L_j^H with d_j >= 0, where mask_j zeroes row and column j.
Checks everything in exact arithmetic and writes the Lean file OUT (the data module KLearn/Data54.lean).
Usage: python gen_lean.py G.npy X.npy OUT
"""
import sys
from fractions import Fraction as Fr
import numpy as np

G, X = np.load(sys.argv[1]), np.load(sys.argv[2])
n, k, r = 5, 4, 3
D1, D2, MU = 10 ** 9, 10 ** 10, Fr(3, 10 ** 9)

def q(x, den): return Fr(round(x * den), den)
class C:  # exact Gaussian rationals
    def __init__(s, a, b=Fr(0)): s.a, s.b = Fr(a), Fr(b)
    def __add__(s, o): return C(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return C(s.a - o.a, s.b - o.b)
    def __mul__(s, o): return C(s.a * o.a - s.b * o.b, s.a * o.b + s.b * o.a)
    def conj(s): return C(s.a, -s.b)
    def inv(s): m = s.a * s.a + s.b * s.b; return C(s.a / m, -s.b / m)
    def ns(s): return s.a * s.a + s.b * s.b
    def __eq__(s, o): return s.a == o.a and s.b == o.b
Z = C(0)

# vectors: G = sum over the top r eigenpairs, psi_i[c] = sqrt(lam_c) conj(V[i, c])
lam, V = np.linalg.eigh(G); idx = np.argsort(lam)[::-1][:r]
P = [[C(q((np.sqrt(lam[c]) * np.conj(V[i, c])).real, D1), q((np.sqrt(lam[c]) * np.conj(V[i, c])).imag, D1)) for c in idx] for i in range(n)]
dot = lambda u, v: sum((a.conj() * b for a, b in zip(u, v)), Z)   # <u|v>
Gr = [[dot(P[i], P[j]) for j in range(n)] for i in range(n)]
t2 = max(Gr[i][j].ns() / (Gr[i][i].a * Gr[j][j].a) for i in range(n) for j in range(n) if i != j)
t0 = Fr(int(float(t2) ** 0.5 * 10 ** 9) + 1, 10 ** 9); assert t0 * t0 >= t2

Y = [[None] * n for _ in range(n)]
for i in range(n):
    Y[i][i] = C(q(X[i, i].real, D2) + MU)
    for j in range(i + 1, n):
        Y[i][j] = C(q(X[i, j].real, D2), q(X[i, j].imag, D2)); Y[j][i] = Y[i][j].conj()
tr = sum((Y[a][b] * Gr[b][a] for a in range(n) for b in range(n)), Z)
assert tr.b == 0 and tr.a < 0, float(tr.a)

def ldl(j):
    """mask_j(Y) = L diag(d) L^H, L unit lower triangular on the indices != j, zero row/column j, d_j = 0."""
    S = [i for i in range(n) if i != j]
    A = [[Y[a][b] for b in S] for a in S]; m = len(S)
    L = [[C(1) if a == b else Z for b in range(m)] for a in range(m)]; d = [Fr(0)] * m
    for c in range(m):
        s = A[c][c] - sum((L[c][p] * L[c][p].conj() * C(d[p]) for p in range(c)), Z)
        assert s.b == 0 and s.a > 0; d[c] = s.a
        for a in range(c + 1, m):
            v = A[a][c] - sum((L[a][p] * C(d[p]) * L[c][p].conj() for p in range(c)), Z)
            L[a][c] = v * C(1 / d[c])
    LL = [[Z] * n for _ in range(n)]; dd = [Fr(0)] * n
    for a in range(m):
        dd[S[a]] = d[a]
        for b in range(m): LL[S[a]][S[b]] = L[a][b]
    for a in range(n):           # exact check of the factorization
        for b in range(n):
            v = sum((LL[a][p] * C(dd[p]) * LL[b][p].conj() for p in range(n)), Z)
            assert v == (Y[a][b] if a != j and b != j else Z)
    return LL, dd

fac = [ldl(j) for j in range(n)]
W = (3 / 8) ** 0.5
print(f"t0 = {t0} = {float(t0):.9f}, t0 - W = {float(t0) - W:.3e}, Tr(YG) = {float(tr.a):.3e}")
print("max digits in L:", max(len(str(x.a)) + len(str(x.b)) for LL, _ in fac for row in LL for x in row))

def lc(x):
    f = lambda v: f"({v.numerator} / {v.denominator} : ℝ)" if v.denominator != 1 else f"({v.numerator} : ℝ)"
    return f"⟨{f(x.a)}, {f(x.b)}⟩"
def lmat(M): return "!![" + "; ".join(", ".join(lc(x) for x in row) for row in M) + "]"
def lvec(v): return "![" + ", ".join(lc(x) for x in v) + "]"
out = ["import KLearn.Basic", "", "/-! Exact data for five states in ℂ³ that are not 4-learnable. Generated by `sim/gen_lean.py`. -/", "",
       "namespace KLearn.Instance54", "", "open Matrix Complex", "", "noncomputable section", "",
       f"/-- Five vectors in ℂ³, in rational coordinates. -/\ndef psi : Fin 5 → Fin 3 → ℂ := ![{', '.join(lvec(v) for v in P)}]", "",
       f"/-- The witness. -/\ndef Y : Matrix (Fin 5) (Fin 5) ℂ := {lmat(Y)}", ""]
for j, (LL, dd) in enumerate(fac):
    out.append(f"def L{j} : Matrix (Fin 5) (Fin 5) ℂ := {lmat(LL)}")
    out.append(f"def d{j} : Fin 5 → ℂ := {lvec([C(x) for x in dd])}")
    out.append("")
out.append(f"/-- The overlap bound. -/\ndef t0 : ℝ := {t0.numerator} / {t0.denominator}")
out.append("\nend\n\nend KLearn.Instance54\n")
open(sys.argv[3], "w").write("\n".join(out))
